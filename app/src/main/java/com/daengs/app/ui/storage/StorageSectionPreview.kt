package com.daengs.app.ui.storage

/**
 * 저장소 탭의 섹션을 **몇 개만 보여 주고 접을 것인가.**
 *
 * ## 왜 이 규칙이 필요한가
 *
 * 저장소 탭이 케어 기록·진료비·대화 보관함을 **한 `LazyColumn` 에** 이어 붙이고 있었다.
 * 기록이 쌓이면 스크롤만 길어진다 — 사용자가 짚은 그 문제다. 실기기에서 재 보니 케어
 * 기록만으로 화면의 60%(131 → 약 630dp, 항목 일곱 개)를 먹고, 진료비가 648dp 로 화면
 * 끝에 걸치고, **대화 보관함은 아예 화면 밖이었다.**
 *
 * 진료비는 이미 「이번 달 합계 · 마지막 방문 + 전체보기」로 접혀 있었다. **그 답을 나머지
 * 둘에도 쓴다** — 탭에는 요약만 두고 자세한 것은 전용 화면이 받는다. 그러면 **탭 높이가
 * 내용과 무관하게 고정된다.**
 *
 * ## 왜 순수 함수인가
 *
 * "몇 개를 보여 주나" 와 "전체보기를 띄우나" 는 **숫자로 잡을 수 있는 규칙**이고, 여기가
 * 어긋나면 화면이 다시 길어진다. 특히 경계가 헷갈린다 — 항목이 딱 [PREVIEW] 개일 때
 * 전체보기를 띄우면 눌러도 같은 것이 나온다.
 */
object StorageSectionPreview {

    /**
     * 탭에서 보여 주는 개수.
     *
     * 둘로 잡았다. 셋이면 케어·보관함이 각각 세 줄이라 탭이 다시 한 화면을 넘는다.
     * 하나면 "목록" 으로 안 읽혀서 전체보기가 있는 줄 모른다.
     */
    const val PREVIEW = 2

    /** 탭에 실제로 그릴 개수. */
    fun shown(total: Int): Int = total.coerceAtMost(PREVIEW)

    /**
     * 「전체보기」를 띄우나.
     *
     * **접힌 게 있을 때만 띄운다.** 항목이 [PREVIEW] 개 이하면 눌러도 같은 것이 나오므로,
     * 그 버튼은 아무것도 안 하는 것처럼 느껴진다.
     *
     * ⚠️ 진료비는 이 규칙에서 **일부러 빠진다.** 거기는 기록이 없어도 전체보기를 남겨
     * 두는데, *"아직 없어요 라고 말하고 전체보기까지 감추면, 유저는 기록이 감춰져"* 있다고
     * 읽기 때문이다 (`VetVisitSection.kt:125`). 진료비는 기간을 바꿔 보는 화면이라
     * "이 기간에 없다" 와 "한 건도 없다" 가 다르고, 케어·보관함은 그 구분이 없다.
     */
    fun showsAll(total: Int): Boolean = total > PREVIEW

    /** 접힌 개수. 「+3개 더」 처럼 쓴다. */
    fun hidden(total: Int): Int = (total - PREVIEW).coerceAtLeast(0)
}
