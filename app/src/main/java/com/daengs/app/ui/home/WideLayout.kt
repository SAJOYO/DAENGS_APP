package com.daengs.app.ui.home

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * 넓은 화면(폴더블 펼침·태블릿) 배치의 기준값.
 *
 * ## 왜 여기에 숫자를 모으나
 *
 * 화면마다 제각각 `if (maxWidth > 600.dp)` 를 쓰면 기기마다 어디는 두 칸이고 어디는
 * 한 칸인 상태가 된다. 기준은 한 군데에만 둔다.
 *
 * ## ⚠️ 여기 dp 는 **화면의 dp 가 아니다**
 *
 * `DaengsTheme` 이 [uiScaleForWindow] 로 `LocalDensity` 를 갈아끼우기 때문에, 합성
 * 안에서 재는 dp 는 **기준 폭(411) 자로 잰 값**이다. 폴드 펼침(777dp·배율 1.25)은
 * 합성 안에서 622dp 로 보인다. 그래서 이 상수들은 화면 dp 가 아니라 그 환산값과 견준다.
 */

/**
 * 두 칸으로 갈 만큼 넓은가를 가르는 선.
 *
 * 폰은 배율 때문에 합성 안에서 411 언저리로 수렴하고(360dp 폰도 424, 430dp 폰도 411),
 * 폴드 펼침이 622 다. 그 사이를 넉넉히 가른다 — 어중간한 폭에서 두 칸으로 갈라지면
 * 한 칸이 너무 좁아진다.
 */
val WIDE_BREAKPOINT: Dp = 560.dp

/**
 * 한 칸으로 갈 때 콘텐츠가 넘지 않을 폭.
 *
 * 넓은 화면에서 카드를 폭에 맞춰 늘리면 한 줄짜리 글이 가로로 길게 퍼져 읽기 나쁘고
 * 속이 휑해 보인다. **폰과 같은 폭으로 두고 가운데에 놓는다** — 남는 자리는 바탕색이다.
 *
 * 411 이 아니라 조금 넉넉한 것은, 폰에서도 폭이 424~440 으로 잡히는 기기가 있어
 * 그것들까지 잘라 내면 지금 폰에서 보이는 모습이 바뀌기 때문이다.
 */
val CONTENT_MAX_WIDTH: Dp = 460.dp

/**
 * 하단바 대신 **왼쪽 세로 레일**을 쓸 창인가.
 *
 * **가로일 때만이다.** 세로 공간이 411dp 뿐이라 하단바가 설 자리가 없어서, 눕히면
 * 바가 통째로 사라지고 다른 탭으로 갈 방법이 없었다.
 *
 * **폭이 아니라 가로세로 비로 정한다.** 폴더블을 세로로 펼치면 622×746 이라 넓지만
 * 하단바가 설 자리가 있다. 넓다고 레일로 세워 봤더니 화면이 더 넓어 보이기만 하고
 * 나을 게 없었다 (사용자 결정 2026-09-08). 넓이([WIDE_BREAKPOINT])와는 다른 질문이다.
 */
fun usesNavRail(maxWidth: Dp, maxHeight: Dp): Boolean = maxWidth > maxHeight

/**
 * 상단바를 접을 만큼 **세로가 짧은가.**
 *
 * 가로에서는 로고가 두 줄인 상단바가 화면의 3분의 1을 먹었다. 폴더블을 세로로 펼친
 * 경우(746dp)는 세로가 넉넉하므로 상단바를 그대로 둔다 — 레일을 쓰는 것과 상단바를
 * 접는 것은 **다른 질문이다.**
 */
fun hidesTopBar(maxHeight: Dp): Boolean = maxHeight < 520.dp

/**
 * 세로가 짧을 때 방에 **먼저 떼어 주는** 높이.
 *
 * 미니룸은 이 저장소가 담당하는 물건이라 카드에 밀려 사라지게 두지 않는다.
 *
 * 200 은 플립 커버(본문 311dp)에서 **찍어 보고 고른 값이다.** 260 으로 두면
 * 방은 크지만 아래 챗봇 카드가 흰 띠 한 줄로만 남아서, "아래 더 있다" 가
 * 아니라 그냥 긁힌 것처럼 보였다. 200 이면 카드 제목과 "대화 열기" 가 읽혀
 * 스크롤이 있다는 게 보인다 (사용자 결정 2026-09-11).
 *
 * **방이 이 높이로 잘리지는 않는다.** `RoomGeometry.of` 가 상자에 맞춰 스스로
 * 줄어든다 — 여기 값은 그 상자의 세로다.
 */
val ROOM_MIN_HEIGHT: Dp = 200.dp

/**
 * 방 아래 카드 덩어리가 먹는 높이. **실측값이다.**
 *
 * `CardSlotHeight` 146 + 사이 10 + 산책 요약 161 + 아래 10 = 327.
 * 산책 요약은 내용에 따라 늘어나므로 상수로 못 박을 수 없고, 여기 값은
 * "한 화면에 들어가나" 를 가르는 데만 쓴다 — 배치에는 안 쓴다.
 */
val CARDS_BLOCK_HEIGHT: Dp = 327.dp

/**
 * 홈을 **스크롤 한 칸**으로 돌릴 만큼 세로가 짧은가.
 *
 * 갤럭시 Z 플립 커버 화면(본문 337dp)에서 **미니룸이 통째로 사라졌다.** 방이
 * `weight(1f)` 로 남는 높이를 가져가는데 카드가 먼저 다 먹어서 10dp 가 남았다.
 * 플렉스 모드에서 쓸 수 있는 위쪽 절반(본문 412dp)도 **같은 병이다** —
 * 세로가 짧다. 그래서 판정은 하나다.
 *
 * **[hidesTopBar] 와 다른 질문이다.** 상단바를 접는 것과 방이 들어가느냐는
 * 따로 논다. [WIDE_BREAKPOINT] 와도 독립이다 — 폭은 두 칸이냐, 세로는
 * 스크롤이냐.
 *
 * 경계가 카드와 방 최소치의 **합**인 것은 [ROOM_MIN_HEIGHT] 를 만졌을 때
 * 경계가 같이 움직이게 하려는 것이다. 숫자를 따로 적으면 둘이 어긋난다.
 */
fun homeScrolls(contentHeight: Dp): Boolean =
    contentHeight < CARDS_BLOCK_HEIGHT + ROOM_MIN_HEIGHT
